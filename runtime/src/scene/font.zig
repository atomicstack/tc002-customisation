pub const glyphs: [95][glyph_h]u8 = blk: {
    @setEvalBranchQuota(40000);
    var g: [95][glyph_h]u8 = undefined;
    for (src, 0..) |rows, i| {
        for (rows, 0..) |row, r| {
            var bits: u8 = 0;
            for (row, 0..) |ch, c| {
                if (ch == '#') bits |= @as(u8, 1) << @intCast(glyph_w - 1 - c);
            }
            g[i][r] = bits;
        }
    }
    break :blk g;
};

/// the glyph for a byte; anything outside printable ascii draws as `?`.
pub fn glyph(c: u8) *const [glyph_h]u8 {
    const i: usize = if (c >= 0x20 and c <= 0x7e) c - 0x20 else '?' - 0x20;
    return &glyphs[i];
}

/// pixel width of a string: advances between glyphs, no trailing gap.
pub fn textWidth(text: []const u8) usize {
    return if (text.len == 0) 0 else text.len * advance - 1;
}

/// draw text with its top-left corner at (x0, y0); pixels outside the panel are skipped.
pub fn blit(rgb: *geometry.Rgb, x0: i32, y0: i32, text: []const u8, colour: [3]u8) void {
    var x = x0;
    for (text) |c| {
        const g = glyph(c);
        for (g, 0..) |row, r| {
            const y = y0 + @as(i32, @intCast(r));
            if (y < 0 or y >= geometry.height) continue;
            for (0..glyph_w) |col| {
                if ((row >> @intCast(glyph_w - 1 - col)) & 1 == 0) continue;
                const px = x + @as(i32, @intCast(col));
                if (px < 0 or px >= geometry.width) continue;
                const o = geometry.pixelOffset(@intCast(px), @intCast(y));
                rgb[o..][0..3].* = colour;
            }
        }
        x += advance;
    }
}
