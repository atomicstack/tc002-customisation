//! a built-in 5x7 bitmap font covering printable ascii 0x20..0x7e, including lowercase, and a
//! clipped blit into the panel's rgb buffer. glyph rows are five bits wide, bit 4 = leftmost.
const std = @import("std");
const geometry = @import("../panel/geometry.zig");

pub const glyph_w = 5;
pub const glyph_h = 7;
/// horizontal advance: glyph width plus one column of spacing.
pub const advance = 6;

test "every printable character has a glyph and space is empty" {
    var c: u8 = 0x20;
    while (c <= 0x7e) : (c += 1) {
        const g = glyph(c);
        var any = false;
        for (g) |row| {
            try std.testing.expectEqual(@as(u8, 0), row & 0xe0);
            any = any or row != 0;
        }
        if (c == ' ') try std.testing.expect(!any) else try std.testing.expect(any);
    }
}

test "lowercase and uppercase letters differ and non-printables map to the question mark" {
    var c: u8 = 'a';
    while (c <= 'z') : (c += 1) try std.testing.expect(!std.mem.eql(u8, glyph(c), glyph(c - 32)));
    try std.testing.expectEqualSlices(u8, glyph('?'), glyph(0x01));
    try std.testing.expectEqualSlices(u8, glyph('?'), glyph(0xff));
}

test "text width counts advances without a trailing gap" {
    try std.testing.expectEqual(@as(usize, 0), textWidth(""));
    try std.testing.expectEqual(@as(usize, 5), textWidth("a"));
    try std.testing.expectEqual(@as(usize, 11), textWidth("ab"));
    try std.testing.expectEqual(@as(usize, 47), textWidth("13:05:09"));
}

test "blit clips at every edge and lights something inside" {
    var rgb = geometry.black_rgb;
    blit(&rgb, -3, -2, "hi", .{ 255, 0, 0 });
    blit(&rgb, 49, 13, "xy", .{ 0, 255, 0 });
    blit(&rgb, 200, 200, "far", .{ 0, 0, 255 });
    try std.testing.expect(!std.mem.eql(u8, &geometry.black_rgb, &rgb));
    // the partly clipped 'i' at x = 3 must have lit its column somewhere in rows 0..4
    var lit = false;
    for (0..5) |y| lit = lit or rgb[geometry.pixelOffset(3 + 2, y)] != 0;
    try std.testing.expect(lit);
}

test "a few known glyph rows" {
    try std.testing.expectEqual(@as(u8, 0b11111), glyph('A')[3]);
    try std.testing.expectEqual(@as(u8, 0b01110), glyph('1')[6]);
    try std.testing.expectEqual(@as(u8, 0b00100), glyph('?')[6]);
    try std.testing.expectEqual(@as(u8, 0b01110), glyph('g')[6]);
}

