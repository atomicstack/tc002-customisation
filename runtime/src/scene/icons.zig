//! the built-in icon set: 8x8 monochrome glyphs, tinted at draw time, named so a document can ask
//! for one without carrying its pixels. authored as text art the way `font.zig` is, because a
//! mistake in a picture is only visible if you can see the picture.
//!
//! monochrome on purpose. at 8x8 there is no room for shading, and a glyph that takes the element's
//! colour fits whatever the document is already doing; anything that needs its own colours is a
//! sprite, which an integration uploads.
