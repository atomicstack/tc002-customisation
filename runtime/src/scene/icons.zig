pub const count = set.len;

/// the rows as bits, built once at compile time: bit 7 is the leftmost column
pub const bitmaps = blk: {
    @setEvalBranchQuota(20000);
    var out: [count][size]u8 = undefined;
    for (set, 0..) |icon, i| {
        for (icon.art, 0..) |row, y| {
            var bits: u8 = 0;
            for (0..size) |x| {
                if (row[x] == '#') bits |= @as(u8, 0x80) >> @intCast(x);
            }
            out[i][y] = bits;
        }
    }
    break :blk out;
};

pub fn indexOf(name: []const u8) ?u8 {
    for (set, 0..) |icon, i| if (std.mem.eql(u8, icon.name, name)) return @intCast(i);
    return null;
}

pub fn nameOf(index: u8) []const u8 {
    return if (index < count) set[index].name else "?";
}

test "every icon is eight rows of eight, named once, and draws something" {
    var seen: [count][]const u8 = undefined;
    for (set, 0..) |icon, i| {
        try std.testing.expectEqual(@as(usize, size), icon.art.len);
        var any = false;
        for (icon.art) |row| {
            try std.testing.expectEqual(@as(usize, size), row.len);
            for (row) |c| try std.testing.expect(c == '#' or c == '.');
            any = any or std.mem.indexOfScalar(u8, row, '#') != null;
        }
        try std.testing.expect(any); // a blank icon is a mistake, not a design
        try std.testing.expect(icon.name.len > 0 and icon.name.len <= 16);
        for (seen[0..i]) |other| try std.testing.expect(!std.mem.eql(u8, other, icon.name));
        seen[i] = icon.name;
    }
    try std.testing.expect(count >= 48);
}

test "a name resolves to its bitmap and back" {
    const i = indexOf("thermometer").?;
    try std.testing.expectEqualStrings("thermometer", nameOf(i));
    try std.testing.expect(indexOf("nonesuch") == null);
    try std.testing.expectEqualStrings("?", nameOf(count));
    // the top row of the sun has one lit pixel, at column three
    const sun = bitmaps[indexOf("sun").?];
    try std.testing.expectEqual(@as(u8, 0b00010000), sun[0]);
}
